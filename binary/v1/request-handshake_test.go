package ignite3

import (
	"bytes"
	"reflect"
	"testing"
)

func TestRequestHandshake_WriteTo(t *testing.T) {
	tests := []struct {
		name    string
		r       *RequestHandshake
		want    int64
		wantW   []byte
		wantErr bool
	}{
		{
			name: "1",
			r:    NewRequestHandshake(3, 0, 0, "ignite", "ignite"),
			want: 75,	// 67 + 4 + 4 ?
			wantW: []byte{0x49, 0x47, 0x4e, 0x49, 0x0, 0x0, 0x0, 0x43, 0x3, 0x0, 0x0, 0x2,
				0xc4, 0x01, 0x4, 0x3,
				0xae, 0x61, 0x75, 0x74, 0x68, 0x6e, 0x2d, 0x69, 0x64, 0x65, 0x6e, 0x74, 0x69, 0x74, 0x79,
				0xa6, 0x69, 0x67, 0x6e, 0x69, 0x74, 0x65,
				0xac, 0x61, 0x75, 0x74, 0x68, 0x6e, 0x2d, 0x73, 0x65, 0x63, 0x72, 0x65, 0x74,
				0xa6, 0x69, 0x67, 0x6e, 0x69, 0x74, 0x65,
				0xaa, 0x61, 0x75, 0x74, 0x68, 0x6e, 0x2d, 0x74, 0x79, 0x70, 0x65,
				0xa5, 0x62, 0x61, 0x73, 0x69, 0x63},
		},
	}
	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			w := &bytes.Buffer{}
			got, err := tt.r.WriteTo(w)
			if (err != nil) != tt.wantErr {
				t.Errorf("RequestHandshake.WriteTo() error = %v, wantErr %v", err, tt.wantErr)
				return
			}
			if got != tt.want {
				t.Errorf("RequestHandshake.WriteTo() = %v", got)
				t.Errorf("RequestHandshake.WriteTo() want = %v", tt.want)
			}
			if gotW := w.Bytes(); !reflect.DeepEqual(w.Bytes(), tt.wantW) {
				t.Errorf("RequestHandshake.WriteTo() = %#v", gotW)
				t.Errorf("RequestHandshake.WriteTo() want = %#v", tt.wantW)
			}
		})
	}
}
